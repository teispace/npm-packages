/**
 * Shift-JIS table for Kanji mode.
 *
 * Importing this module registers the table with the core encoder as a side
 * effect. Once registered, `encode(text, { kanji: true })` will use Kanji mode
 * wherever it produces a smaller symbol — 13 bits per character against 24 for
 * the same character as UTF-8 bytes, a 46% saving on Japanese text.
 *
 * ```ts
 * import { encode } from 'teiqr/core';
 * import 'teiqr/kanji';
 *
 * encode('こんにちは世界', { kanji: true }); // version 1 instead of version 2
 * ```
 *
 * ### Why this is a separate entry point
 * The table is 23520 characters of Shift-JIS, and shipping it in the core entry
 * would add ~10 kB gzipped to every bundle to serve the small fraction of
 * users encoding Japanese. Keeping it opt-in means the core stays small and
 * nobody pays for what they do not use.
 *
 * ### How it is stored
 * Sorted by Shift-JIS value and split into two varint streams — the Shift-JIS
 * deltas (almost all 1) and zigzag code-point deltas — then base64'd. Two
 * separate streams rather than interleaved pairs because it lets the
 * compressor model each one independently, which measured 10,342 B gzipped
 * against 13,620 B interleaved and 19,183 B for the obvious encoding. The
 * table is decoded lazily on first use, so importing this module costs
 * nothing until a Kanji symbol is actually encoded.
 */

