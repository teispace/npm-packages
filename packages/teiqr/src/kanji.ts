/** Decoded on first lookup, then reused. */
let table: Map<number, number> | null = null;

const decodePacked = (): Map<number, number> => {
  const raw =
    typeof atob === 'function'
      ? Uint8Array.from(atob(PACKED), (c) => c.charCodeAt(0))
      : // Node before atob was global, and any runtime without it.
        new Uint8Array(Buffer.from(PACKED, 'base64'));

  let pos = 0;
  const readVarint = (): number => {
    let result = 0;
    let shift = 0;
    let byte: number;
    do {
      byte = raw[pos++];
      result |= (byte & 0x7f) << shift;
      shift += 7;
    } while (byte & 0x80);
    return result >>> 0;
  };
  // Zigzag: maps signed deltas onto unsigned so small negatives stay one byte.
  const unzigzag = (n: number): number => (n >>> 1) ^ -(n & 1);

  const count = readVarint();

  const sjisDeltas = new Uint16Array(count);
  for (let i = 0; i < count; i++) sjisDeltas[i] = readVarint();

  const map = new Map<number, number>();
  let codePoint = 0;
  let sjis = 0;
  for (let i = 0; i < count; i++) {
    sjis += sjisDeltas[i];
    codePoint += unzigzag(readVarint());
    // First mapping wins, matching how the table was generated.
    if (!map.has(codePoint)) map.set(codePoint, sjis);
  }
  return map;
};

registerKanjiTable((codePoint: number): number | undefined => {
  table ??= decodePacked();
  return table.get(codePoint);
});

/** Number of code points the table covers. Decodes the table if it has not been already. */
export const kanjiTableSize = (): number => {
  table ??= decodePacked();
  return table.size;
};
